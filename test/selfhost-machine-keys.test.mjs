import assert from 'node:assert/strict';
import {createHash, randomBytes} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdtemp, readFile, rm, stat} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {test} from 'node:test';
import {machineIdentities} from '../dist/src/selfhost/machine-identity.mjs';
import {singleOrganizationSessionSource} from '../dist/src/selfhost/indexing.mjs';
import {createLocalSessionStore} from '../dist/src/sessions/local-store.mjs';
import {maskPatterns} from '../dist/src/sessions/credential-patterns.mjs';

test('operator-generated machine credentials bind service ownership across rotation and tenant scope', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'selfhost-machine-'));
  t.after(() => rm(dir, {recursive: true, force: true}));
  const destination = join(dir, 'support.env');
  const args = ['deploy/helm/machine-key.mjs', 'support', 'http://localhost:8092', destination];
  const verifier = execFileSync(process.execPath, args, {encoding: 'utf8'}).trim();
  const contents = await readFile(destination, 'utf8');
  const key = /^OPENCRAWL_TOKEN=(.+)$/m.exec(contents)[1];
  assert.equal((await stat(destination)).mode & 0o777, 0o600);
  assert.equal(maskPatterns(key), '[REDACTED]');
  assert.equal(verifier, 'support:' + createHash('sha256').update(key).digest('hex'));
  assert.throws(() => execFileSync(process.execPath, args, {stdio: 'pipe'}));
  assert.equal(await readFile(destination, 'utf8'), contents);
  const secondKey = 'oca1_' + randomBytes(32).toString('hex');
  const secondVerifier = 'support:' + createHash('sha256').update(secondKey).digest('hex');
  const service = machineIdentities('org_test', verifier + ',' + secondVerifier);
  const {principal} = service.identify(key);
  assert.equal(service.authorize(principal).userId, service.identify(secondKey).principal.userId);
  assert.throws(() => service.authorize({...principal}), /Machine identity required/);
  assert.equal(service.sharedInstallations[0].userId, principal.userId);
  const rotated = machineIdentities('org_test', secondVerifier);
  assert.equal(rotated.identify(key).status, 401);
  assert.equal(rotated.identify(secondKey).principal.userId, principal.userId);
  assert.notEqual(machineIdentities('org_other', verifier).identify(key).principal.userId, principal.userId);
  assert.throws(() => machineIdentities('org_test', verifier + ',' + verifier), /duplicate/);
  assert.throws(() => machineIdentities('org_test', key), /verifier/);
  const source = singleOrganizationSessionSource({organizationId: 'org_test', search:{endpoint:'http://localhost:9200',environment:'selfhost',tenantId:'org_test'}}, createLocalSessionStore(dir), 'sessions');
  const worker = await source.resolve({sourceId:source.sourceId});
  assert.deepEqual(await worker.resolvePrincipal({batch: {owner: principal}}), {tenantId:principal.tenantId, userId:principal.userId});
  await assert.rejects(worker.resolvePrincipal({batch:{owner:{...principal,tenantId:'org_other'}}}), /scope denied/);
});
