import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {test} from 'node:test';
import {machineKeys} from '../dist/src/identity/machine-keys.mjs';
import {createLocalIdentity} from '../dist/src/identity/better-auth.mjs';
import {maskPatterns} from '../dist/src/sessions/credential-patterns.mjs';
import {applicationDatabaseFixture} from './fixtures/application-database.mjs';

test('machine keys store only a verifier and authorize each installation and request independently', async t => {
  const database = await applicationDatabaseFixture(t);
  const org = 'org_selfhost';
  const identity = await createLocalIdentity({url:'http://localhost:8092',secret:'x'.repeat(32),database,organizationId:org});
  await identity.ready();
  const service = identity.machines;
  const otherReplica = machineKeys(database.identityPool, org);
  const otherOrg = machineKeys(database.identityPool, 'org_other');
  const issued = await service.create('Support');
  assert.equal(maskPatterns(issued.secret), '[REDACTED]');
  const {rows} = await database.identityPool.query('SELECT * FROM opencrawl_machine_keys');
  assert.equal(rows[0].verifier,createHash('sha256').update(issued.secret).digest('hex'));
  assert.ok(!JSON.stringify(rows).includes(issued.secret));
  assert.deepEqual(await otherReplica.list(),[issued.key]);
  assert.deepEqual(await otherOrg.list(),[]);
  assert.equal((await otherOrg.identify(issued.secret)).status,401);
  assert.equal((await otherReplica.identify('invalid')).status,401);
  const {principal} = await otherReplica.identify(issued.secret);
  assert.equal((await otherReplica.authorize(principal)).userId,principal.userId);
  await assert.rejects(otherReplica.authorize({...principal}),/denied/);
  assert.equal((await service.sharedInstallations())[0].userId,principal.userId);
  await otherOrg.revoke(issued.key.id);
  assert.equal((await otherReplica.identify(issued.secret)).status,200);
  const second = await service.create('Second');
  await service.revoke(issued.key.id);
  await service.revoke(issued.key.id);
  assert.equal((await otherReplica.identify(issued.secret)).status,401);
  await assert.rejects(otherReplica.authorize(principal),/denied/);
  assert.equal((await otherReplica.identify(second.secret)).status,200);
  const replacement = await service.create('Support');
  assert.notEqual((await service.identify(replacement.secret)).principal.userId,principal.userId);
  await assert.rejects(service.create('  '),{status:400});
  await assert.rejects(service.create('Support'),{status:409});
});
