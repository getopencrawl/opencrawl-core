import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createSessionIngest,digest} from '../dist/src/sessions/ingest.mjs';
import {createControls} from '../dist/src/sessions/controls.mjs';
import {sourceBatchIdentity} from '../dist/src/sessions/event-identity.mjs';
import {libraryOperations} from '../dist/src/sessions/library-http.mjs';
import {batchDocuments} from '../dist/src/sessions/indexer.mjs';
import {memorySessionStore} from './session-store-fixture.mjs';
const owner={tenantId:'selfhost-team',userId:'owner'},peer={...owner,userId:'peer'},outside={tenantId:'other-team',userId:'owner'};
const batch={schemaVersion:1,owner,installationId:'mac',sessionId:'native-cursor-chat',harness:'cursor',origin:'unknown',captureMode:'live',events:[{id:'prompt',kind:'message',sequence:1,data:{role:'user',content:[{type:'text',text:'Cursor harbor acceptance'}]}}],attachments:[]};
test('self-host Cursor ingestion, namespace, controls and projection preserve trusted ownership',async()=>{
 const store=memorySessionStore(),ingest=createSessionIngest({store}),controls=createControls({store,prefix:'capture-v1'});
 const receipt=await ingest.putBatch(owner,batch);assert.equal(receipt.stored,true);
 assert.equal((await ingest.getBatch(owner,{...batch,batchId:receipt.batchId})).harness,'cursor');
 assert.equal(await ingest.getBatch(outside,{...batch,batchId:receipt.batchId}),null);
 await assert.rejects(ingest.putBatch(outside,batch),/owner|identity|principal|Invalid/i);
 const key=`capture-v1/tenants/${digest(owner.tenantId)}/users/${digest(owner.userId)}/cursor/${digest(batch.installationId)}/${digest(batch.sessionId)}/${receipt.batchId}.json.gz`;
 assert.equal(sourceBatchIdentity('capture-v1',key).harness,'cursor');
 const docs=batchDocuments({prefix:'capture-v1',key,batch,principal:owner}).map(x=>x.document);
 assert.equal(docs[0].harness,'cursor');assert.equal(docs[0].text,'Cursor harbor acceptance');assert.equal(docs[0].userId,owner.userId);
 await controls.update(owner,'sessions','cursor',batch.sessionId,()=>({visibility:'private',deletedAt:null}));
 assert.equal((await controls.read(owner,'sessions','cursor',batch.sessionId)).visibility,'private');
 assert.equal(await controls.read(peer,'sessions','cursor',batch.sessionId),null);
 await controls.update(owner,'sessions','cursor',batch.sessionId,()=>({visibility:'private',deletedAt:'2026-11-14T00:00:00Z'}));
 assert.equal((await ingest.putBatch(owner,{...batch,events:[{...batch.events[0],id:'later'}]})).discarded,'session_deleted');
 assert(libraryOperations['sessions/read'].safeParse({userId:'owner',harness:'cursor',sessionId:batch.sessionId}).success);
 assert(libraryOperations['sessions/visibility'].safeParse({harness:'cursor',sessionId:batch.sessionId,visibility:'private'}).success);
 assert(libraryOperations['sessions/delete'].safeParse({harness:'cursor',sessionId:batch.sessionId}).success);
 assert.equal(libraryOperations['memories/read'].safeParse({userId:'owner',harness:'cursor',path:'memory/MEMORY.md'}).success,false);
});
